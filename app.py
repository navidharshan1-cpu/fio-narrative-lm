import json, math, os

import pandas as pd
import streamlit as st
import torch

BASE_NAME = "distilgpt2"
LM_DIR = os.environ.get("LM_DIR", "fio_lm_model")
LM_REPO = os.environ.get("LM_REPO", "")
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
if DEVICE == "cpu":
    torch.set_num_threads(max(1, os.cpu_count() or 1))

st.set_page_config(page_title="FIO Narrative Language Model", page_icon="📝", layout="wide")


# ------------------------------------------------------------------ loading
@st.cache_resource(show_spinner="Loading the language models…")
def load_models():
    from transformers import AutoTokenizer, AutoModelForCausalLM
    if os.path.exists(os.path.join(LM_DIR, "config.json")):
        ft_path = LM_DIR
    elif LM_REPO:
        from huggingface_hub import snapshot_download
        ft_path = snapshot_download(LM_REPO, token=os.environ.get("HF_TOKEN") or None)
    else:
        return None
    tok = AutoTokenizer.from_pretrained(BASE_NAME)
    tok.pad_token = tok.eos_token
    base = AutoModelForCausalLM.from_pretrained(BASE_NAME).to(DEVICE).eval()
    tuned = AutoModelForCausalLM.from_pretrained(ft_path).to(DEVICE).eval()
    info_path = os.path.join(ft_path, "training_info.json")
    info = json.load(open(info_path)) if os.path.exists(info_path) else {}
    return tok, base, tuned, info, ft_path


@torch.no_grad()
def generate(model, tok, prompt, max_new_tokens, temperature, top_p, seed):
    torch.manual_seed(seed)
    enc = tok(prompt, return_tensors="pt").to(DEVICE)
    out = model.generate(**enc, max_new_tokens=max_new_tokens, do_sample=True, temperature=temperature, top_p=top_p,
                         repetition_penalty=1.1, pad_token_id=tok.eos_token_id)
    return " ".join(tok.decode(out[0][enc["input_ids"].shape[1]:], skip_special_tokens=True).split())


@torch.no_grad()
def perplexity(model, tok, prompt, continuation):
    """Perplexity of the generated continuation only, with the prompt as context (prompt tokens are not scored)."""
    p_ids = tok(prompt, return_tensors="pt")["input_ids"]
    c_ids = tok(" " + continuation, return_tensors="pt")["input_ids"]
    if c_ids.shape[1] == 0:
        return float("nan")
    ids = torch.cat([p_ids, c_ids], dim=1).to(DEVICE)
    labels = ids.clone(); labels[:, : p_ids.shape[1]] = -100
    return math.exp(model(input_ids=ids, labels=labels).loss.item())


RESULTS_DIRS = []          # filled after the model is loaded: <model>/results first, then the app folder


def find(name):
    for d in RESULTS_DIRS:
        path = os.path.join(d, name)
        if os.path.exists(path):
            return path
    return None


def read_csv(name):
    path = find(name)
    return pd.read_csv(path) if path else None


SYNTHETIC = "⚠️ SYNTHETIC TEXT – generated by a language model. It describes no real event and is not a police record."
PROMPTS = [
    "On patrol in the area, officers observed",
    "Officers conducted a traffic stop of a",
    "While conducting a walk and talk, officers engaged in a conversation with",
    "Officers responded to a call for",
]

# ------------------------------------------------------------------ layout
st.title("Fine-tuned Language Model for Police Field-Report Narratives")
st.caption("DistilGPT-2 before and after fine-tuning on redacted Boston Police FIO narratives (2024) · "
           "MAAI 902 project · research and teaching use only")

with st.sidebar:
    st.header("Generation settings")
    max_new = st.slider("New tokens", 20, 120, 70, 10)
    temperature = st.slider("Temperature", 0.1, 1.5, 0.8, 0.1, help="Higher = more random")
    top_p = st.slider("Top-p (nucleus)", 0.5, 1.0, 0.9, 0.05)
    seed = st.number_input("Random seed", 0, 9999, 42, help="Same seed + settings = same text for both models")
    st.divider()
    st.caption(f"Device: {'GPU' if DEVICE == 'cuda' else 'CPU'}")

loaded = load_models()
if loaded is None:
    st.error("The fine-tuned model was not found. Set the secret `LM_REPO` to your Hugging Face model repo, or put the "
             "unzipped `fio_lm_model/` folder next to app.py.")
    st.stop()
tok, base, tuned, info, ft_path = loaded
RESULTS_DIRS[:] = [os.path.join(ft_path, "results"), "."]

tab_gen, tab_exp, tab_about = st.tabs(["📝 Compare generations", "📊 Model performance", "ℹ️ About"])

with tab_gen:
    st.subheader("Same prompt, two models")
    st.write("Both models continue your prompt with identical settings and the same random seed, so any difference "
             "comes from fine-tuning.")
    choice = st.selectbox("Example prompt", PROMPTS)
    prompt = st.text_input("Prompt", value=choice)
    if st.button("Generate", type="primary", disabled=not prompt.strip()):
        with st.spinner("Generating…"):
            out_base = generate(base, tok, prompt, max_new, temperature, top_p, int(seed))
            out_tuned = generate(tuned, tok, prompt, max_new, temperature, top_p, int(seed))
        c1, c2 = st.columns(2)
        with c1:
            st.markdown("#### Base DistilGPT-2 (no fine-tuning)")
            st.write(f"**{prompt}** {out_base}")
            st.caption(f"Perplexity of the generated words under the fine-tuned model: "
                       f"{perplexity(tuned, tok, prompt, out_base):.1f}")
        with c2:
            run = info.get("run", "fine-tuned")
            st.markdown(f"#### Fine-tuned on FIO narratives ({run})")
            st.write(f"**{prompt}** {out_tuned}")
            st.caption(f"Perplexity of the generated words under the fine-tuned model: "
                       f"{perplexity(tuned, tok, prompt, out_tuned):.1f}")
        st.warning(SYNTHETIC)
        st.caption("Lower perplexity means the generated words look more like real FIO narratives. Only the generated "
                   "words are scored, not your prompt.")
    if info:
        st.divider()
        m1, m2, m3 = st.columns(3)
        m1.metric("Validation loss – base model", f"{info['base_val_loss']:.3f}",
                  help=f"perplexity {math.exp(info['base_val_loss']):.1f}")
        m2.metric("Validation loss – fine-tuned", f"{info['final_val_loss']:.3f}",
                  f"{info['final_val_loss'] - info['base_val_loss']:+.3f}", delta_color="inverse",
                  help=f"perplexity {math.exp(info['final_val_loss']):.1f}")
        m3.metric("Perplexity reduction", f"{math.exp(info['base_val_loss']) / math.exp(info['final_val_loss']):.1f}×")

with tab_exp:
    test = info.get("test")
    if test:
        st.subheader("Performance of the final model on the held-out test set")
        cfg = info.get("config", {})
        st.write(f"Trained on {info.get('corpus', 'redacted FIO narratives')}. Learning rate {cfg.get('lr')}, batch "
                 f"{cfg.get('batch_size')}, {int(cfg.get('warmup_ratio', 0) * 100)}% warm-up, weight decay "
                 f"{cfg.get('weight_decay')}, early stopping (patience {cfg.get('early_stopping_patience')}): stopped "
                 f"at epoch {info.get('stopped_epoch', 0):.2f}, best checkpoint at epoch {info.get('best_epoch', 0):.2f}.")
        b, f = test["base"], test["fine_tuned"]
        k1, k2, k3, k4 = st.columns(4)
        k1.metric("Test perplexity", f"{f['perplexity']:.1f}", f"{f['perplexity'] - b['perplexity']:+.1f} vs base",
                  delta_color="inverse")
        k2.metric("Next-token accuracy (top-1)", f"{f['next-token accuracy (top-1)']:.1%}",
                  f"{(f['next-token accuracy (top-1)'] - b['next-token accuracy (top-1)']) * 100:+.1f} pts")
        k3.metric("ROUGE-L F1", f"{f['ROUGE-L F1']:.3f}", f"{f['ROUGE-L F1'] - b['ROUGE-L F1']:+.3f}")
        k4.metric("Domain-style rate", f"{f['domain-style rate']:.0%}",
                  f"{(f['domain-style rate'] - b['domain-style rate']) * 100:+.0f} pts")
        rows = [("Loss", "loss", "{:.3f}"), ("Perplexity", "perplexity", "{:.1f}"),
                ("Next-token accuracy (top-1)", "next-token accuracy (top-1)", "{:.1%}"),
                ("Next-token accuracy (top-5)", "next-token accuracy (top-5)", "{:.1%}"),
                ("ROUGE-L precision", "ROUGE-L precision", "{:.3f}"), ("ROUGE-L recall", "ROUGE-L recall", "{:.3f}"),
                ("ROUGE-L F1", "ROUGE-L F1", "{:.3f}"), ("BLEU-4", "BLEU-4", "{:.3f}"),
                ("Distinct-2 (variety)", "distinct-2", "{:.3f}"), ("Repetition rate", "repetition rate", "{:.3f}"),
                ("Domain-style rate", "domain-style rate", "{:.0%}"), ("Ends naturally", "ends naturally", "{:.0%}")]
        st.dataframe(pd.DataFrame([{"metric": n, "base DistilGPT-2": fmt.format(b[k]), "fine-tuned": fmt.format(f[k])}
                                   for n, k, fmt in rows if k in b and k in f]).set_index("metric"),
                     use_container_width=True)
        st.caption("Next-token accuracy is the language-model form of accuracy; ROUGE-L F1 compares each completion "
                   "of an unseen test narrative with its real continuation. ROUGE and BLEU stay low because a "
                   "narrative can continue in many valid ways – they are for comparing the two models.")
        for img, cap in [("final_metrics_comparison.png", "Base vs fine-tuned on the held-out test set"),
                         ("final_training_curves.png", "Training and validation loss with early stopping, and the "
                                                       "learning-rate schedule"),
                         ("rouge_distribution.png", "ROUGE-L F1 of every test completion")]:
            path = find(img)
            if path:
                st.image(path, caption=cap, use_container_width=True)
        if info.get("trained_on"):
            st.caption(f"Model trained on {info['trained_on']} · best checkpoint at step {info.get('best_step')} · "
                       f"train/test loss gap {info.get('train_test_loss_gap', float('nan')):+.3f}")
        comp = read_csv("test_completions.csv")
        if comp is not None:
            st.markdown("**Completions of unseen test narratives** (first 15 words given)")
            st.dataframe(comp[["model", "prompt", "reference", "generated", "rouge_f"]].head(20),
                         use_container_width=True, hide_index=True)
            st.caption(SYNTHETIC)
    else:
        st.info("This model has no test metrics yet. Run FIO_LM_Final_Model.ipynb and upload its model files to "
                "Hugging Face to show the final model's performance here.")

with tab_about:
    st.subheader("About")
    st.markdown("""
**Task.** Adapt a pretrained HuggingFace language model to the language of police field reports and evaluate it
against the base model.

**Domain and data.** Free-text narratives from the Boston Police Department's 2024 Field Interrogation and
Observation (FIO) records (Analyze Boston, PDDL public-domain licence), split 80/10/10 into training, validation and
test sets. Names masked by the publisher, officer names, street addresses, neighbourhoods and phone numbers were
replaced with placeholders such as `[REDACTED]` and `[ADDRESS]` before training.

**Model.** DistilGPT-2 (82 M parameters), fine-tuned as a causal language model on 128-token blocks with the
HuggingFace `Trainer`: learning rate 1e-4 with warm-up and linear decay, weight decay 0.01, batch size 8, and early
stopping on validation loss with the best checkpoint restored.

**Responsible use.** All generated text is synthetic and must not be presented as a real police record. The source
narratives contain demographic descriptors that a language model can reproduce, so outputs may reflect biases in
how reports were written.
""")
