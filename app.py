"""
FIO Narrative Language Model – Streamlit app
Fine-tuning assignment · Navi Dharshan B (1716785) and partner

Compares DistilGPT-2 before and after fine-tuning on redacted Boston Police FIO narratives, and shows the
hyperparameter experiments. Every generated text is synthetic and labelled as such.

Model: set LM_REPO to the Hugging Face repo holding the fine-tuned model (e.g. "dharshan3119/fio-narrative-distilgpt2"),
or put the unzipped fio_lm_model/ folder next to this file.
Results: experiment_results.csv, generations.csv, all_loss_curves.png, loss_log.csv next to this file (optional).
"""
import json, math, os

import pandas as pd
import streamlit as st
import torch

BASE_NAME = "distilgpt2"
LM_DIR = os.environ.get("LM_DIR", "fio_lm_model")
LM_REPO = os.environ.get("LM_REPO", "")
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
if DEVICE == "cpu":
    torch.set_num_threads(max(1, os.cpu_count() or 1))

st.set_page_config(page_title="FIO Narrative Language Model", page_icon="📝", layout="wide")


# ------------------------------------------------------------------ loading
@st.cache_resource(show_spinner="Loading the language models…")
def load_models():
    from transformers import AutoTokenizer, AutoModelForCausalLM
    if os.path.exists(os.path.join(LM_DIR, "config.json")):
        ft_path = LM_DIR
    elif LM_REPO:
        from huggingface_hub import snapshot_download
        ft_path = snapshot_download(LM_REPO, token=os.environ.get("HF_TOKEN") or None)
    else:
        return None
    tok = AutoTokenizer.from_pretrained(BASE_NAME)
    tok.pad_token = tok.eos_token
    base = AutoModelForCausalLM.from_pretrained(BASE_NAME).to(DEVICE).eval()
    tuned = AutoModelForCausalLM.from_pretrained(ft_path).to(DEVICE).eval()
    info_path = os.path.join(ft_path, "training_info.json")
    info = json.load(open(info_path)) if os.path.exists(info_path) else {}
    return tok, base, tuned, info


@torch.no_grad()
def generate(model, tok, prompt, max_new_tokens, temperature, top_p, seed):
    torch.manual_seed(seed)
    enc = tok(prompt, return_tensors="pt").to(DEVICE)
    out = model.generate(**enc, max_new_tokens=max_new_tokens, do_sample=True, temperature=temperature, top_p=top_p,
                         repetition_penalty=1.1, pad_token_id=tok.eos_token_id)
    return " ".join(tok.decode(out[0][enc["input_ids"].shape[1]:], skip_special_tokens=True).split())


@torch.no_grad()
def perplexity(model, tok, text):
    enc = tok(text, return_tensors="pt").to(DEVICE)
    if enc["input_ids"].shape[1] < 2:
        return float("nan")
    return math.exp(model(**enc, labels=enc["input_ids"]).loss.item())


def read_csv(name):
    return pd.read_csv(name) if os.path.exists(name) else None


SYNTHETIC = "⚠️ SYNTHETIC TEXT – generated by a language model. It describes no real event and is not a police record."
PROMPTS = [
    "On patrol in the area, officers observed",
    "Officers conducted a traffic stop of a",
    "While conducting a walk and talk, officers engaged in a conversation with",
    "Officers responded to a call for",
]

# ------------------------------------------------------------------ layout
st.title("Fine-tuned Language Model for Police Field-Report Narratives")
st.caption("DistilGPT-2 before and after fine-tuning on 600 redacted Boston Police FIO narratives (2024) · "
           "fine-tuning assignment · research and teaching use only")

with st.sidebar:
    st.header("Generation settings")
    max_new = st.slider("New tokens", 20, 120, 70, 10)
    temperature = st.slider("Temperature", 0.1, 1.5, 0.8, 0.1, help="Higher = more random")
    top_p = st.slider("Top-p (nucleus)", 0.5, 1.0, 0.9, 0.05)
    seed = st.number_input("Random seed", 0, 9999, 42, help="Same seed + settings = same text for both models")
    st.divider()
    st.caption(f"Device: {'GPU' if DEVICE == 'cuda' else 'CPU'}")

loaded = load_models()
if loaded is None:
    st.error("The fine-tuned model was not found. Set the secret `LM_REPO` to your Hugging Face model repo, or put the "
             "unzipped `fio_lm_model/` folder next to app.py.")
    st.stop()
tok, base, tuned, info = loaded

tab_gen, tab_exp, tab_about = st.tabs(["📝 Compare generations", "📈 Experiments", "ℹ️ About"])

with tab_gen:
    st.subheader("Same prompt, two models")
    st.write("Both models continue your prompt with identical settings and the same random seed, so any difference "
             "comes from fine-tuning.")
    choice = st.selectbox("Example prompt", PROMPTS)
    prompt = st.text_input("Prompt", value=choice)
    if st.button("Generate", type="primary", disabled=not prompt.strip()):
        with st.spinner("Generating…"):
            out_base = generate(base, tok, prompt, max_new, temperature, top_p, int(seed))
            out_tuned = generate(tuned, tok, prompt, max_new, temperature, top_p, int(seed))
        c1, c2 = st.columns(2)
        with c1:
            st.markdown("#### Base DistilGPT-2 (no fine-tuning)")
            st.write(f"**{prompt}** {out_base}")
            st.caption(f"Perplexity of this text under the fine-tuned model: "
                       f"{perplexity(tuned, tok, prompt + ' ' + out_base):.1f}")
        with c2:
            run = info.get("run", "fine-tuned")
            st.markdown(f"#### Fine-tuned on FIO narratives ({run})")
            st.write(f"**{prompt}** {out_tuned}")
            st.caption(f"Perplexity of this text under the fine-tuned model: "
                       f"{perplexity(tuned, tok, prompt + ' ' + out_tuned):.1f}")
        st.warning(SYNTHETIC)
        st.caption("Lower perplexity means the text looks more like the FIO narratives the model was trained on.")
    if info:
        st.divider()
        m1, m2, m3 = st.columns(3)
        m1.metric("Validation loss – base model", f"{info['base_val_loss']:.3f}",
                  help=f"perplexity {math.exp(info['base_val_loss']):.1f}")
        m2.metric("Validation loss – fine-tuned", f"{info['final_val_loss']:.3f}",
                  f"{info['final_val_loss'] - info['base_val_loss']:+.3f}", delta_color="inverse",
                  help=f"perplexity {math.exp(info['final_val_loss']):.1f}")
        m3.metric("Perplexity reduction", f"{math.exp(info['base_val_loss']) / math.exp(info['final_val_loss']):.1f}×")

with tab_exp:
    st.subheader("Hyperparameter experiments")
    st.write("Each run starts from the same pretrained weights and changes one hyperparameter from the reference "
             "(learning rate 5e-4, 5 epochs, batch size 4, block size 128).")
    if os.path.exists("all_loss_curves.png"):
        st.image("all_loss_curves.png", caption="Training (lines) and validation (markers) loss for every run",
                 use_container_width=True)
    res = read_csv("experiment_results.csv")
    if res is not None:
        st.markdown("**Results**")
        st.dataframe(res, use_container_width=True, hide_index=True)
    gens = read_csv("generations.csv")
    if gens is not None:
        st.markdown("**Generations from the notebook** (prompt: *On patrol in the area, officers observed*)")
        st.dataframe(gens, use_container_width=True, hide_index=True)
        st.caption(SYNTHETIC)
    if res is None and gens is None:
        st.info("Add experiment_results.csv, generations.csv and all_loss_curves.png from fio_lm_results.zip to the "
                "repository to show the experiments here.")

with tab_about:
    st.subheader("About")
    st.markdown("""
**Task.** Fine-tune a pretrained HuggingFace language model on a domain, vary hyperparameters one at a time, and
compare training behaviour and output quality.

**Domain and data.** Free-text narratives from the Boston Police Department's 2024 Field Interrogation and
Observation (FIO) records (Analyze Boston, PDDL public-domain licence). 600 narratives were used (540 training,
60 validation). Names masked by the publisher, officer names, street addresses, neighbourhoods and phone numbers were
replaced with placeholders such as `[REDACTED]` and `[ADDRESS]` before training.

**Model.** DistilGPT-2 (82 M parameters), fine-tuned as a causal language model on 128-token blocks with the
HuggingFace `Trainer`; loss logged every 5 steps with a `TrainerCallback`.

**Responsible use.** All generated text is synthetic and must not be presented as a real police record. The source
narratives contain demographic descriptors that a language model can reproduce, so outputs may reflect biases in
how reports were written.
""")
